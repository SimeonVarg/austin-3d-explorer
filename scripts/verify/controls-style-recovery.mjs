import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../../js/controls.js',import.meta.url),'utf8');
const start=source.indexOf('  function tick(ts) {'),end=source.indexOf('    const sprint =',start);
let prefix=source.slice(start,end)+'}\nglobalThis.tick=tick;';
if(process.argv.includes('--break'))prefix=prefix.replace('if (!map.style) return;','');
let scheduled=0,scans=0;
const map={style:{}};
const scan=()=>{if(!map.style)throw Error('scan accessed absent style');scans++;};
const scope=vm.createContext({map,requestAnimationFrame:()=>++scheduled,performance:{now:()=>0},outerMaybeScan:scan,trunkMaybeScan:scan});
vm.runInContext('let rafId,lastTs=null,simTime=0; const DT_BAIL=.25,DT_MAX=.064;\n'+prefix,scope);
scope.tick(0);map.style=null;scope.tick(16);
assert.equal(scans,0,'no collision/source work during loss');
assert.equal(scheduled,2,'keep a future frame scheduled');
assert.equal(vm.runInContext('lastTs',scope),16,'clock stays current');
scope.tick(1000);map.style={};scope.tick(1016);
assert.equal(scans,2,'both scans resume when the style returns');
assert.equal(vm.runInContext('simTime',scope),.016,'loss interval is not integrated into movement');
console.log('PASS: absent style pauses scans, rearms frames and preserves resume delta');
