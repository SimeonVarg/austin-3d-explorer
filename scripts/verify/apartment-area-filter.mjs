import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const source = fs.readFileSync(new URL('../../js/slopes-apartments.js', import.meta.url), 'utf8');
const start = source.indexOf('  const sameJSON =');
const end = source.indexOf('  function* filterChanges', start);
assert.ok(start >= 0 && end > start);
let serializations = 0;
const context = vm.createContext({ JSON: { stringify(value) { serializations++; return JSON.stringify(value); } } });
vm.runInContext(source.slice(start, end), context);
const ring = Array.from({ length: 3000 }, (_, index) => [-97 + index / 10000, 30 + index / 20000]);
const geometry = { type: 'MultiPolygon', coordinates: [[ring]] };
const clause = ['>', ['distance', geometry], 0];
const copy = structuredClone(clause);
const before = ['has', 'id'];
const combined = ['all', ['all', before, copy], ['!=', ['get', 'name'], 'Retained']];
assert.equal(context.containsClause(combined, clause), true);
assert.equal(context.containsClause(['literal', [clause]], clause), false);
assert.equal(context.containsClause(['>', ['distance', { type: 'MultiPolygon', coordinates: [] }], 0], clause), false);
assert.equal(context.sameFilter(clause, copy), true);
copy[1][1].coordinates[0][0][0][0] += 0.01;
assert.equal(context.sameFilter(clause, copy), false);
copy[1][1].coordinates[0][0][0][0] -= 0.01;
const untouched = JSON.stringify(combined);
const stripped = context.stripClause(combined, clause);
assert.equal(JSON.stringify(stripped), JSON.stringify(['all', before, ['!=', ['get', 'name'], 'Retained']]));
assert.equal(JSON.stringify(combined), untouched);
assert.equal(context.stripClause(['literal', [clause]], clause)[0], 'literal');
assert.equal(context.stripClause(clause, clause), null);
assert.equal(serializations, 0, 'geometry filter equality/strip must not stringify giant polygons at every node');
const hook = 'window.maskTest={setup(data){_data=data;},hideGeometry,hideGeometrySteps};';
const scope = vm.createContext({window:{location:{search:'?slopes=0'}},location:{search:'?slopes=0'},URLSearchParams,console});
const hookAt = source.lastIndexOf('})();');
vm.runInContext(source.slice(0,hookAt)+hook+source.slice(hookAt),scope);
const mask = scope.window.maskTest;
const buildings = Array.from({length:3},(_,index)=>({id:'mask-'+index,name:'Mask '+index,footprint:{ring:[[-97.74+index/1000,30.28],[-97.7398+index/1000,30.28],[-97.7398+index/1000,30.2802],[-97.74+index/1000,30.2802],[-97.74+index/1000,30.28]]}}));
mask.setup({buildings});
const steps=mask.hideGeometrySteps(1);
let yielded=0,result;
do{result=steps.next();if(!result.done)yielded++;}while(!result.done);
assert.equal(yielded,buildings.length,'one cooperative mask yield per footprint');
assert.strictEqual(mask.hideGeometry(1),result.value,'only the completed mask is cached');
const partial=mask.hideGeometrySteps(0);
assert.equal(partial.next().done,false);
partial.return();
const restart=mask.hideGeometrySteps(0);
assert.equal(restart.next().done,false,'cancelled partial mask must not publish an incomplete cache');
restart.return();
assert.equal(mask.hideGeometry(0).coordinates.length,buildings.length,'synchronous caller gets the same complete footprint mask');
console.log('PASS: large geometry clauses compare and strip without JSON serialization, input mutation or loss of nested foreign clauses; literals remain opaque');
