# How many blobs are actually DRAWN on one roof. A flat cap is the wrong shape:
# 46 units is nothing on a 7,000 m^2 apartment block and far too many on a
# 200 m^2 shopfront. Scaling with area keeps the DENSITY roughly constant, which
# is what the eye reads, and the biggest are kept first so what survives is what
# shows from the air. The `d` keep-order then lets the density knob thin these
# further at run time without a re-bake.
def MAX_FOR(area_m2):
    return int(max(10, min(96, area_m2 / 85.0)))


# LOD. `t=0` is what reads from flying altitude and draws from z14.5; `t=1` is
