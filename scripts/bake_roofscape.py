# -*- coding: utf-8 -*-
"""The roofscape: what is actually ON the roofs, read off the photograph.

THE PROBLEM, stated as a measurement. This app is a FLYOVER. The camera spends
most of its time above the city looking down, so the surface the viewer sees
most is not facades — it is roofs. And `bake_detail.py` derives every roof
colour as `adjust_light(wall, -0.12)`: the roof is its own wall, 12% darker.
2,346 of the 2,453 buildings therefore render as a flat brown lid with nothing
on it. Fly West Campus and you get a field of brown lumps.

Fly the real West Campus and you get the opposite: bright white TPO membrane,
and every one of those white decks carpeted in tight rows of split-system
condensers, one per apartment. The single loudest error was never the missing
clutter — it was the COLOUR. See `docs/ROOFSCAPE.md` for the before/after.

WHAT IS FACTUAL HERE AND WHAT IS NOT. Every drawn feature carries `src`:

    src = "m"   MEASURED. Its position, size, orientation and colour are read
                off z20 Esri nadir imagery (0.129 m/px — a 1.4 m condenser is
                11 px across, which is why this works at all). The deck colour
                of every building is measured this way, without exception.
    src = "g"   GENERATED by rule, because the photograph showed nothing there.
                Only ever a stair/lift overrun, and only on buildings tall
                enough to require one. Rule, count and reasoning below.

There is no third category. Nothing here is invented decoration on a roof the
photograph says is empty.

THE VOCABULARY, derived from the imagery before anything was drawn (Playbook
rule 1 — the crops it was read off are listed in docs/ROOFSCAPE.md):

    deck     the roof surface itself, inset inside the parapet, in its OWN
             measured colour. One polygon per building. This is the pass.
    cond     a split-system condenser, ~1.4 m square, ~1.0 m tall. West Campus
             roofs carry these in paired rows of 6-14.
    unit     an AHU / large condenser / roof plant box, 5-34 m^2, ~1.7 m.
    fan      a round exhaust or cooling-tower fan. Welch's plant deck has a row
             of eight in a line.
    duct     a run of ductwork or a pipe rack: long, thin, low.
    plant    a dark equipment field or louvre screen — the big dark rectangles
             over the lab blocks. Low and wide, not a building.
    phouse   a stair/lift/mechanical penthouse: large, bright, and TALL enough
             to break the silhouette. The only kind that is ever generated.
    pool     rooftop water. Detected by colour, and there really are that many.

WHY NOT ONE BOX PER DETECTED BLOB, EVERYWHERE. Roof clutter is a per-building
cost multiplied by thousands of buildings, and the app has already auto-detected
~30 fps and dropped itself into the `performance` preset. So:
  * every feature carries `t` (LOD tier) and `d` (a keep-order in 0..1), and
    js/roofs.js splits them across two layers with different minzooms;
  * `MAX_FOR(area)` caps the clutter on any one roof, biggest kept first;
  * decks are 0.25 m tall, so they add a top face and almost no side geometry.
Measured cost is in docs/ROOFSCAPE.md. It is not free and it is not guessed.

SCOPE IS THE CORE ONLY. This reads the current snapshot, whose bbox is UT +
West Campus + The Drag (scripts/config.sh). A building outside that box gets no
deck and no clutter — it keeps the plain `rd` lid it has today. That is
deliberate: the radius pass is making the outer ring a cheap tier and it must
stay cheap. See docs/ROOFSCAPE.md "Beyond the core".

Usage:  python scripts/bake_roofscape.py [--remeasure] [--report]

  --remeasure   re-read the imagery instead of reusing data/roof_survey.json.
                Same split as bake_roofs.py, for the same reason: reading 2,400
                roofs off z20 tiles takes minutes, and the geometry — which is
                what needs iterating against renders — takes seconds.
"""
